x = 20
print("Value of x is",x)      #20

x += 5
print("Value of x is",x)      #25

x -= 5
print("Value of x is",x)      #20

x *= 5
print("Value of x is",x)      #100


x /= 5
print("Value of x is",x)      #20.0

x //= 5
print("Value of x is",x)      #20.0/5 = 4.0

x **= 5
print("Value of x is",x)      #1024

x %= 5
print("Value of x is",x)      #4.0


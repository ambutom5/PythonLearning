# Sample Input
# 5

# Sample Output
# 1
# 22
# 333
# 4444


for i in range(1,int(input())):
    print(((10**i-1)//9)*i)


# For i = 1: (10**1 - 1)//9 * 1 = (9//9)*1 =    1
# For i = 2: (100 - 1)//9 * 2 = (99//9)*2 =     11*2 = 22
# For i = 3: (1000 - 1)//9 * 3 = (999//9)*3 =   111*3 = 333
# For i = 4: (10000 - 1)//9 * 4 = (9999//9)*4 = 1111*4 = 4444



for i in range(1,int(input())+1):
    print(((10**i)//9)**2)


# i = 1 → (10**1)//9 = 1, 1**2 = 1 → prints 1
# i = 2 → (10**2)//9 = 11, 11**2 = 121 → prints 121
# i = 3 → (10**3)//9 = 111, 111**2 = 12321 → prints 12321
# i = 4 → (10**4)//9 = 1111, 1111**2 = 1234321 → prints 1234321
# i = 5 → (10**5)//9 = 11111, 11111**2 = 123454321 → prints 123454321